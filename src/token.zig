pub const Token = struct {
    tag: TokenType,
    lexeme: []const u8,
    line: usize,
    column: usize,

    pub fn format(
        self: Token,
        comptime fmt: []const u8,
        options: std.fmt.FormatOptions,
        writer: anytype,
    ) !void {
        _ = fmt;
        _ = options;
        try writer.print("{s}('{s}') at {d}:{d}", .{
            @tagName(self.tag),
            self.lexeme,
            self.line,
            self.column,
        });
    }
};

